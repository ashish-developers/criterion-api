// Request shapes for organisation user management. Bulk rows are accepted loosely here and
// validated field by field in userAdminService so every row gets its own error messages.
const { z, uuid, phone, listQuery } = require("./common");

const list = listQuery.extend({
  role: z.string().trim().max(40).optional(),
  status: z.enum(["active", "invited", "inactive"]).optional(),
});

const looseText = (max) => z.union([z.string().max(max), z.number()]).optional().nullable().transform((v) => (v === null || v === undefined ? undefined : String(v)));
const row = z.object({
  row: z.coerce.number().int().min(1).max(100000).optional(),
  name: looseText(300),
  email: looseText(300),
  phone: looseText(40),
  role: looseText(80),
  sendInvite: z.union([z.boolean(), z.string().max(10)]).optional().nullable(),
  organization: looseText(200),
});
const rows = z.array(row).min(1, "Add at least one user").max(500, "At most 500 users can be added at once");

const validateRows = z.object({ rows });
const bulkCreate = z.object({
  rows,
  // Generated by the client once per submission; resubmitting the same key replays the result.
  idempotencyKey: z.string().regex(/^[A-Za-z0-9_-]{8,80}$/, "Invalid request key"),
  source: z.enum(["manual", "csv"]).default("manual"),
});
const update = z
  .object({
    name: z.string().trim().min(2, "Enter the full name").max(120).optional(),
    phone: z.union([phone, z.literal(""), z.null()]).optional(),
    role: z.string().trim().max(40).optional(),
  })
  .refine((d) => d.name !== undefined || d.phone !== undefined || d.role !== undefined, { message: "Nothing to update" });
const status = z.object({ active: z.boolean() });
const userId = z.object({ id: uuid });
const batchId = z.object({ batchId: uuid });

module.exports = { list, validateRows, bulkCreate, update, status, userId, batchId };
